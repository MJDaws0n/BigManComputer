// ============================================================================
// BMC → Assembly Generator
// Generates real assembly for educational purposes, showing how BMC
// instructions map to actual CPU operations.
// ============================================================================

function bmcToAsm(code, target) {
    const lines = code.split('\n');
    const parsed = parseBmcLines(lines);
    if (parsed.error) return '; Error: ' + parsed.error;

    switch (target) {
        case 'arm64-macos': return genARM64(parsed, true);
        case 'arm64-linux': return genARM64(parsed, false);
        case 'x86_64-linux': return genX86(parsed, false);
        case 'x86_64-macos': return genX86(parsed, true);
        default: return genARM64(parsed, true);
    }
}

function parseBmcLines(lines) {
    const instructions = [];
    const labels = {};
    const dataEntries = [];

    // First pass: collect labels and instructions
    let addr = 0;
    for (const raw of lines) {
        let line = raw.replace(/;.*$/, '').trim();
        if (!line) continue;

        let label = null;
        if (line.includes(':')) {
            const parts = line.split(':');
            label = parts[0].trim();
            line = parts.slice(1).join(':').trim();
        }

        if (label) labels[label] = addr;

        if (!line) { addr++; continue; }

        const tokens = line.split(/\s+/);
        const op = tokens[0].toUpperCase();
        const operand = tokens[1] || null;
        instructions.push({ addr, op, operand, label });
        addr++;
    }

    // Second pass: resolve operands
    for (const inst of instructions) {
        if (inst.operand && labels[inst.operand] !== undefined) {
            inst.resolvedAddr = labels[inst.operand];
        }
    }

    return { instructions, labels };
}

// ============================================================================
// ARM64 Assembly Generation
// ============================================================================

function genARM64(parsed, isMacos) {
    const { instructions } = parsed;
    const prefix = isMacos ? '_' : '';
    const syscallNum = isMacos ? '0x2000000' : '0';
    const writeNo = isMacos ? '0x2000004' : '64';
    const readNo = isMacos ? '0x2000003' : '63';
    const exitNo = isMacos ? '0x2000001' : '93';

    let asm = '';
    asm += '; ============================================================\n';
    asm += '; BMC Program — ARM64 Assembly\n';
    asm += '; Target: ' + (isMacos ? 'macOS (Apple Silicon)' : 'Linux (AArch64)') + '\n';
    asm += '; Generated by Big Man Computer\n';
    asm += '; ============================================================\n';
    asm += '; Register usage:\n';
    asm += ';   w19 = ACC  (accumulator)\n';
    asm += ';   w20 = MAR  (memory address register)\n';
    asm += ';   w21 = MDR  (memory data register)\n';
    asm += ';   x22 = base pointer to memory[] array\n';
    asm += '; ============================================================\n\n';

    asm += '.global ' + prefix + 'main\n';
    asm += '.align 4\n\n';

    // Data section
    asm += '.data\n';
    asm += 'memory:     .space 400          ; 100 x 4-byte cells\n';
    asm += 'outbuf:     .space 16           ; output buffer\n';
    asm += 'inbuf:      .space 64           ; input buffer\n';
    asm += 'newline:    .ascii "\\n"\n\n';

    // Pre-initialise memory with DAT values
    let hasData = false;
    for (const inst of instructions) {
        if (inst.op === 'DAT') {
            hasData = true;
            break;
        }
    }

    // Text section
    asm += '.text\n\n';

    // Main entry
    asm += prefix + 'main:\n';
    asm += '    ; Preserve callee-saved registers\n';
    asm += '    stp x29, x30, [sp, #-16]!\n';
    asm += '    stp x19, x20, [sp, #-16]!\n';
    asm += '    stp x21, x22, [sp, #-16]!\n\n';
    asm += '    ; Initialise registers\n';
    asm += '    mov w19, #0                 ; ACC = 0\n';
    asm += '    mov w20, #0                 ; MAR = 0\n';
    asm += '    mov w21, #0                 ; MDR = 0\n';
    asm += '    adrp x22, memory@PAGE\n';
    asm += '    add x22, x22, memory@PAGEOFF ; x22 = &memory[0]\n\n';

    // Initialise DAT values
    for (const inst of instructions) {
        if (inst.op === 'DAT') {
            const val = parseInt(inst.operand) || 0;
            asm += '    ; Initialise memory[' + inst.addr + '] = ' + val + '\n';
            asm += '    mov w21, #' + val + '\n';
            asm += '    str w21, [x22, #' + (inst.addr * 4) + ']\n';
        }
    }
    if (hasData) asm += '\n';

    // Generate code for each instruction
    for (const inst of instructions) {
        const addrLabel = 'addr_' + inst.addr;
        asm += addrLabel + ':';

        // Show the original label if any
        const originalLabels = [];
        for (const [lbl, a] of Object.entries(parsed.labels)) {
            if (a === inst.addr) originalLabels.push(lbl);
        }
        if (originalLabels.length > 0) {
            asm += '    ; [' + originalLabels.join(', ') + ']';
        }
        asm += '\n';

        switch (inst.op) {
            case 'LDA':
                asm += '    ; LDA ' + (inst.operand || '') + ' — Load memory into ACC\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '       ; MAR = address\n';
                asm += '    ldr w19, [x22, w20, uxtw #2]  ; ACC = memory[MAR]\n\n';
                break;
            case 'STA':
                asm += '    ; STA ' + (inst.operand || '') + ' — Store ACC to memory\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '       ; MAR = address\n';
                asm += '    str w19, [x22, w20, uxtw #2]  ; memory[MAR] = ACC\n\n';
                break;
            case 'ADD':
                asm += '    ; ADD ' + (inst.operand || '') + ' — ACC = ACC + memory[addr]\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n';
                asm += '    ldr w21, [x22, w20, uxtw #2]  ; MDR = memory[MAR]\n';
                asm += '    add w19, w19, w21              ; ACC = ACC + MDR\n\n';
                break;
            case 'SUB':
                asm += '    ; SUB ' + (inst.operand || '') + ' — ACC = ACC - memory[addr]\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n';
                asm += '    ldr w21, [x22, w20, uxtw #2]\n';
                asm += '    sub w19, w19, w21              ; ACC = ACC - MDR\n\n';
                break;
            case 'MUL':
                asm += '    ; MUL ' + (inst.operand || '') + ' — ACC = ACC * memory[addr]\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n';
                asm += '    ldr w21, [x22, w20, uxtw #2]\n';
                asm += '    mul w19, w19, w21              ; ACC = ACC * MDR\n\n';
                break;
            case 'DIV':
                asm += '    ; DIV ' + (inst.operand || '') + ' — ACC = ACC / memory[addr]\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n';
                asm += '    ldr w21, [x22, w20, uxtw #2]\n';
                asm += '    sdiv w19, w19, w21             ; ACC = ACC / MDR\n\n';
                break;
            case 'MOD':
                asm += '    ; MOD ' + (inst.operand || '') + ' — ACC = ACC % memory[addr]\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n';
                asm += '    ldr w21, [x22, w20, uxtw #2]\n';
                asm += '    sdiv w9, w19, w21\n';
                asm += '    msub w19, w9, w21, w19         ; ACC = ACC - (ACC/MDR)*MDR\n\n';
                break;
            case 'AND':
                asm += '    ; AND ' + (inst.operand || '') + ' — ACC = ACC & memory[addr]\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n';
                asm += '    ldr w21, [x22, w20, uxtw #2]\n';
                asm += '    and w19, w19, w21\n\n';
                break;
            case 'OR':
                asm += '    ; OR ' + (inst.operand || '') + ' — ACC = ACC | memory[addr]\n';
                asm += '    mov w20, #' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n';
                asm += '    ldr w21, [x22, w20, uxtw #2]\n';
                asm += '    orr w19, w19, w21\n\n';
                break;
            case 'NOT':
                asm += '    ; NOT — ACC = 999 - ACC\n';
                asm += '    mov w21, #999\n';
                asm += '    sub w19, w21, w19\n\n';
                break;
            case 'INP':
                asm += '    ; INP — Read integer from stdin into ACC\n';
                asm += '    mov x0, #0                     ; fd = stdin\n';
                asm += '    adrp x1, inbuf@PAGE\n';
                asm += '    add x1, x1, inbuf@PAGEOFF\n';
                asm += '    mov x2, #63                    ; max bytes\n';
                asm += '    mov x16, #' + readNo + '       ; SYS_read\n';
                asm += '    svc #0\n';
                asm += '    ; Convert ASCII to integer (simple atoi)\n';
                asm += '    adrp x1, inbuf@PAGE\n';
                asm += '    add x1, x1, inbuf@PAGEOFF\n';
                asm += '    mov w19, #0                    ; ACC = 0\n';
                asm += '    mov w9, #10\n';
                asm += 'inp_loop_' + inst.addr + ':\n';
                asm += '    ldrb w10, [x1], #1\n';
                asm += '    sub w10, w10, #48              ; ASCII to digit\n';
                asm += '    cmp w10, #9\n';
                asm += '    b.hi inp_done_' + inst.addr + '\n';
                asm += '    mul w19, w19, w9\n';
                asm += '    add w19, w19, w10\n';
                asm += '    b inp_loop_' + inst.addr + '\n';
                asm += 'inp_done_' + inst.addr + ':\n\n';
                break;
            case 'OUT':
                asm += '    ; OUT — Print ACC as integer to stdout\n';
                asm += '    ; Integer to ASCII conversion\n';
                asm += '    adrp x1, outbuf@PAGE\n';
                asm += '    add x1, x1, outbuf@PAGEOFF\n';
                asm += '    add x1, x1, #15                ; start at end of buffer\n';
                asm += '    mov w9, #10\n';
                asm += '    mov w10, w19                   ; working copy\n';
                asm += '    mov x2, #0                     ; digit count\n';
                asm += 'out_loop_' + inst.addr + ':\n';
                asm += '    udiv w11, w10, w9\n';
                asm += '    msub w12, w11, w9, w10         ; remainder\n';
                asm += '    add w12, w12, #48              ; to ASCII\n';
                asm += '    strb w12, [x1], #-1\n';
                asm += '    mov w10, w11\n';
                asm += '    add x2, x2, #1\n';
                asm += '    cbnz w10, out_loop_' + inst.addr + '\n';
                asm += '    add x1, x1, #1                 ; point to first digit\n';
                asm += '    mov x0, #1                     ; fd = stdout\n';
                asm += '    mov x16, #' + writeNo + '      ; SYS_write\n';
                asm += '    svc #0\n';
                asm += '    ; Print newline\n';
                asm += '    mov x0, #1\n';
                asm += '    adrp x1, newline@PAGE\n';
                asm += '    add x1, x1, newline@PAGEOFF\n';
                asm += '    mov x2, #1\n';
                asm += '    mov x16, #' + writeNo + '\n';
                asm += '    svc #0\n\n';
                break;
            case 'OTC':
                asm += '    ; OTC — Output ACC as ASCII character\n';
                asm += '    adrp x1, outbuf@PAGE\n';
                asm += '    add x1, x1, outbuf@PAGEOFF\n';
                asm += '    and w9, w19, #0xFF\n';
                asm += '    strb w9, [x1]\n';
                asm += '    mov x0, #1                     ; stdout\n';
                asm += '    mov x2, #1                     ; 1 byte\n';
                asm += '    mov x16, #' + writeNo + '\n';
                asm += '    svc #0\n\n';
                break;
            case 'BRA':
                asm += '    ; BRA ' + (inst.operand || '') + ' — Unconditional branch\n';
                asm += '    b addr_' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n\n';
                break;
            case 'BRZ':
                asm += '    ; BRZ ' + (inst.operand || '') + ' — Branch if ACC == 0\n';
                asm += '    cbz w19, addr_' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n\n';
                break;
            case 'BRP':
                asm += '    ; BRP ' + (inst.operand || '') + ' — Branch if ACC >= 0\n';
                asm += '    cmp w19, #0\n';
                asm += '    b.ge addr_' + (inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0) + '\n\n';
                break;
            case 'HLT':
                asm += '    ; HLT — Exit program\n';
                asm += '    mov x0, #0                     ; exit code 0\n';
                asm += '    mov x16, #' + exitNo + '       ; SYS_exit\n';
                asm += '    svc #0\n\n';
                break;
            case 'DAT':
                asm += '    ; DAT ' + (inst.operand || '0') + ' — data storage (initialised above)\n\n';
                break;
            default:
                asm += '    ; Unknown: ' + inst.op + '\n\n';
        }
    }

    // Epilogue (in case no HLT reached)
    asm += 'exit:\n';
    asm += '    mov x0, #0\n';
    asm += '    mov x16, #' + exitNo + '\n';
    asm += '    svc #0\n';

    return asm;
}

// ============================================================================
// x86_64 Assembly Generation
// ============================================================================

function genX86(parsed, isMacos) {
    const { instructions } = parsed;
    const prefix = isMacos ? '_' : '';
    const writeNo = isMacos ? '0x2000004' : '1';
    const readNo = isMacos ? '0x2000003' : '0';
    const exitNo = isMacos ? '0x2000001' : '60';
    const syscallInst = 'syscall';

    let asm = '';
    asm += '; ============================================================\n';
    asm += '; BMC Program — x86_64 Assembly\n';
    asm += '; Target: ' + (isMacos ? 'macOS (Intel)' : 'Linux (AMD64)') + '\n';
    asm += '; Generated by Big Man Computer\n';
    asm += '; ============================================================\n';
    asm += '; Register usage:\n';
    asm += ';   r12d = ACC  (accumulator)\n';
    asm += ';   r13d = MAR  (memory address register)\n';
    asm += ';   r14d = MDR  (memory data register)\n';
    asm += ';   r15  = base pointer to memory[] array\n';
    asm += '; ============================================================\n\n';

    asm += '.global ' + prefix + 'main\n\n';

    // Data section
    if (isMacos) {
        asm += '.section __DATA,__data\n';
    } else {
        asm += '.section .data\n';
    }
    asm += 'memory:     .space 400          ; 100 x 4-byte cells\n';
    asm += 'outbuf:     .space 16           ; output buffer\n';
    asm += 'inbuf:      .space 64           ; input buffer\n';
    asm += 'newline:    .byte 10\n\n';

    // Text section
    if (isMacos) {
        asm += '.section __TEXT,__text\n\n';
    } else {
        asm += '.section .text\n\n';
    }

    asm += prefix + 'main:\n';
    asm += '    push %rbp\n';
    asm += '    mov %rsp, %rbp\n';
    asm += '    push %r12\n';
    asm += '    push %r13\n';
    asm += '    push %r14\n';
    asm += '    push %r15\n\n';
    asm += '    ; Initialise registers\n';
    asm += '    xor %r12d, %r12d             ; ACC = 0\n';
    asm += '    xor %r13d, %r13d             ; MAR = 0\n';
    asm += '    xor %r14d, %r14d             ; MDR = 0\n';
    asm += '    lea memory(%rip), %r15       ; r15 = &memory[0]\n\n';

    // Initialise DAT values
    for (const inst of instructions) {
        if (inst.op === 'DAT') {
            const val = parseInt(inst.operand) || 0;
            asm += '    ; Initialise memory[' + inst.addr + '] = ' + val + '\n';
            asm += '    movl $' + val + ', ' + (inst.addr * 4) + '(%r15)\n';
        }
    }
    asm += '\n';

    for (const inst of instructions) {
        const addrLabel = 'addr_' + inst.addr;
        asm += addrLabel + ':';
        const originalLabels = [];
        for (const [lbl, a] of Object.entries(parsed.labels)) {
            if (a === inst.addr) originalLabels.push(lbl);
        }
        if (originalLabels.length > 0) asm += '    ; [' + originalLabels.join(', ') + ']';
        asm += '\n';

        const rAddr = inst.resolvedAddr !== undefined ? inst.resolvedAddr : 0;

        switch (inst.op) {
            case 'LDA':
                asm += '    ; LDA ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov (%r15,%rax,4), %r12d       ; ACC = memory[MAR]\n\n';
                break;
            case 'STA':
                asm += '    ; STA ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov %r12d, (%r15,%rax,4)       ; memory[MAR] = ACC\n\n';
                break;
            case 'ADD':
                asm += '    ; ADD ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov (%r15,%rax,4), %r14d\n';
                asm += '    add %r14d, %r12d               ; ACC += MDR\n\n';
                break;
            case 'SUB':
                asm += '    ; SUB ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov (%r15,%rax,4), %r14d\n';
                asm += '    sub %r14d, %r12d               ; ACC -= MDR\n\n';
                break;
            case 'MUL':
                asm += '    ; MUL ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov (%r15,%rax,4), %r14d\n';
                asm += '    imul %r14d, %r12d              ; ACC *= MDR\n\n';
                break;
            case 'DIV':
                asm += '    ; DIV ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov (%r15,%rax,4), %r14d\n';
                asm += '    mov %r12d, %eax\n';
                asm += '    cdq\n';
                asm += '    idiv %r14d                     ; EAX = ACC / MDR\n';
                asm += '    mov %eax, %r12d\n\n';
                break;
            case 'MOD':
                asm += '    ; MOD ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov (%r15,%rax,4), %r14d\n';
                asm += '    mov %r12d, %eax\n';
                asm += '    cdq\n';
                asm += '    idiv %r14d                     ; EDX = ACC % MDR\n';
                asm += '    mov %edx, %r12d\n\n';
                break;
            case 'AND':
                asm += '    ; AND ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov (%r15,%rax,4), %r14d\n';
                asm += '    and %r14d, %r12d\n\n';
                break;
            case 'OR':
                asm += '    ; OR ' + (inst.operand || '') + '\n';
                asm += '    mov $' + rAddr + ', %r13d\n';
                asm += '    movslq %r13d, %rax\n';
                asm += '    mov (%r15,%rax,4), %r14d\n';
                asm += '    or %r14d, %r12d\n\n';
                break;
            case 'NOT':
                asm += '    ; NOT — ACC = 999 - ACC\n';
                asm += '    mov $999, %r14d\n';
                asm += '    sub %r12d, %r14d\n';
                asm += '    mov %r14d, %r12d\n\n';
                break;
            case 'INP':
                asm += '    ; INP — Read integer from stdin\n';
                asm += '    mov $' + (isMacos ? '0x2000003' : '0') + ', %rax\n';
                asm += '    mov $0, %rdi                   ; fd = stdin\n';
                asm += '    lea inbuf(%rip), %rsi\n';
                asm += '    mov $63, %rdx\n';
                asm += '    ' + syscallInst + '\n';
                asm += '    ; atoi: convert ASCII to integer\n';
                asm += '    lea inbuf(%rip), %rsi\n';
                asm += '    xor %r12d, %r12d               ; ACC = 0\n';
                asm += '    mov $10, %ecx\n';
                asm += 'inp_loop_' + inst.addr + ':\n';
                asm += '    movzbl (%rsi), %eax\n';
                asm += '    sub $48, %eax                   ; ASCII to digit\n';
                asm += '    cmp $9, %eax\n';
                asm += '    ja inp_done_' + inst.addr + '\n';
                asm += '    imul %ecx, %r12d\n';
                asm += '    add %eax, %r12d\n';
                asm += '    inc %rsi\n';
                asm += '    jmp inp_loop_' + inst.addr + '\n';
                asm += 'inp_done_' + inst.addr + ':\n\n';
                break;
            case 'OUT':
                asm += '    ; OUT — Print ACC as integer\n';
                asm += '    lea outbuf(%rip), %rdi\n';
                asm += '    add $15, %rdi                   ; end of buffer\n';
                asm += '    mov $10, %ecx\n';
                asm += '    mov %r12d, %eax\n';
                asm += '    xor %edx, %edx\n';
                asm += '    mov $0, %r8d                    ; digit count\n';
                asm += 'out_loop_' + inst.addr + ':\n';
                asm += '    xor %edx, %edx\n';
                asm += '    div %ecx                        ; eax/10, remainder in edx\n';
                asm += '    add $48, %dl                    ; to ASCII\n';
                asm += '    mov %dl, (%rdi)\n';
                asm += '    dec %rdi\n';
                asm += '    inc %r8d\n';
                asm += '    test %eax, %eax\n';
                asm += '    jnz out_loop_' + inst.addr + '\n';
                asm += '    inc %rdi                        ; point to first digit\n';
                asm += '    mov $' + (isMacos ? '0x2000004' : '1') + ', %rax\n';
                asm += '    mov $1, %edi\n';
                asm += '    mov %rdi, %rsi                  ; buf pointer\n';
                asm += '    movslq %r8d, %rdx\n';
                asm += '    mov $1, %edi\n';
                asm += '    ' + syscallInst + '\n';
                asm += '    ; newline\n';
                asm += '    mov $' + (isMacos ? '0x2000004' : '1') + ', %rax\n';
                asm += '    mov $1, %edi\n';
                asm += '    lea newline(%rip), %rsi\n';
                asm += '    mov $1, %rdx\n';
                asm += '    ' + syscallInst + '\n\n';
                break;
            case 'OTC':
                asm += '    ; OTC — Output ACC as ASCII char\n';
                asm += '    lea outbuf(%rip), %rsi\n';
                asm += '    mov %r12b, (%rsi)\n';
                asm += '    mov $' + (isMacos ? '0x2000004' : '1') + ', %rax\n';
                asm += '    mov $1, %edi\n';
                asm += '    mov $1, %rdx\n';
                asm += '    ' + syscallInst + '\n\n';
                break;
            case 'BRA':
                asm += '    ; BRA ' + (inst.operand || '') + '\n';
                asm += '    jmp addr_' + rAddr + '\n\n';
                break;
            case 'BRZ':
                asm += '    ; BRZ ' + (inst.operand || '') + '\n';
                asm += '    test %r12d, %r12d\n';
                asm += '    jz addr_' + rAddr + '\n\n';
                break;
            case 'BRP':
                asm += '    ; BRP ' + (inst.operand || '') + '\n';
                asm += '    test %r12d, %r12d\n';
                asm += '    jns addr_' + rAddr + '\n\n';
                break;
            case 'HLT':
                asm += '    ; HLT — Exit program\n';
                asm += '    mov $' + exitNo + ', %rax\n';
                asm += '    xor %edi, %edi\n';
                asm += '    ' + syscallInst + '\n\n';
                break;
            case 'DAT':
                asm += '    ; DAT ' + (inst.operand || '0') + ' — data storage\n\n';
                break;
            default:
                asm += '    ; Unknown: ' + inst.op + '\n\n';
        }
    }

    asm += 'exit:\n';
    asm += '    mov $' + exitNo + ', %rax\n';
    asm += '    xor %edi, %edi\n';
    asm += '    ' + syscallInst + '\n';

    return asm;
}
